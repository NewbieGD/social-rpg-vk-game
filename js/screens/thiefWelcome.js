export function renderThiefWelcome(root, { forced = false, score = null } = {}) {
    root.innerHTML = `
        <div class="thief-welcome">
            <div class="thief-welcome-hero" style="background-image:url('assets/backgrounds/thief-den.jpg')">
                <div class="thief-welcome-shade"></div>
                <div class="thief-welcome-title">Добро пожаловать в тень</div>
                ${score !== null ? `<div class="thief-welcome-score">Экзамен: ${score}/100</div>` : ""}
            </div>
            <div class="thief-welcome-lead">
                ${forced
                    ? "Честная дорога закрылась перед тобой. Но улицы не прощают слабых — и щедро награждают дерзких."
                    : "Ты выбрал(а) путь, о котором другие только шепчутся."}
                Отныне твоё имя — лишь слух в переулках, а каждое твоё решение отзовётся по всей стране.
            </div>
            <div class="thief-welcome-grid">
                ${SECTIONS.map(([icon, title, text], i) => `
                    <div class="thief-welcome-item" style="animation-delay:${120 + i * 90}ms">
                        <div class="thief-welcome-icon">${icon}</div>
                        <div><div class="thief-welcome-item-title">${title}</div><div class="thief-welcome-item-text">${text}</div></div>
                    </div>`).join("")}
            </div>
            <div class="thief-welcome-oath">
                От твоих решений и сделок с другими игроками зависит будущее всей страны: кто будет править улицами, кто сядет в тюрьму, кто взойдёт на трон — и кто с него падёт.
            </div>
            <button class="btn thief-welcome-go" id="thief-welcome-go">🕶 Войти в тёмный мир</button>
        </div>`;
    burstConfetti(root.querySelector(".thief-welcome-hero"), 20);
    root.querySelector("#thief-welcome-go").onclick = () => location.reload();
}
