// Общий механизм: пока элемент реально на экране (root.isConnected), с
// заданным интервалом вызывает refreshFn() заново. Как только экран сменили
// (root убран из DOM тем же innerHTML-заменой, что и везде в игре) —
// интервал сам себя останавливает, никаких утечек.
//
// Придумано для починки «зависших» состояний: дуэль уже сыграна другим
// игроком, голосование уже закрылось, заявка уже кем-то принята — а старый
// экран всё ещё показывает «ждём» просто потому, что ни разу не спросил
// сервер заново. С этой утилитой достаточно один раз подключить нужный
// экран, и «зависание» лечится само по себе на всех экранах разом.
//
// Использование:
//   const stop = startAutoRefresh(root, async () => { ... обновить часть DOM ... }, 5000);
//   (останавливать вручную не нужно — сработает само при уходе с экрана)

export function startAutoRefresh(root, refreshFn, intervalMs = 5000) {
    const interval = setInterval(async () => {
        if (!root || !root.isConnected) {
            clearInterval(interval);
            return;
        }
        try {
            await refreshFn();
        } catch (e) {
            // не критично — просто пропускаем один цикл обновления, не валим экран
        }
    }, intervalMs);
    return interval;
}
