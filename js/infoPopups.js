export function infoButton(key) {
    return `<button type="button" class="info-btn" data-info="${key}" aria-label="Подробнее">ⓘ</button>`;
}

export function bindInfoButtons(root) {
    root.querySelectorAll(".info-btn[data-info]").forEach((btn) => {
        btn.onclick = (e) => {
            e.stopPropagation();
            const info = INFO[btn.dataset.info];
            if (info) showGameStylePopup(info.title, info.text.replace(/\n/g, "<br>"));
        };
    });
}
